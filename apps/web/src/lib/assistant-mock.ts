/**
 * The assistant panel with no API behind it.
 *
 * The panel has to be demonstrable on a phone in a corridor, under `?data=mock`,
 * where the documented promise is that no request leaves the browser. So there is
 * no model here, and the first thing this module does is refuse to pretend there
 * is one: every sentence it produces is assembled out of the synthetic run in
 * `./mock-data.ts`, the panel says so in its header, and nothing below asserts a
 * fact the deterministic side did not already compute.
 *
 * That is not a smaller version of the feature, it is the honest one. What the
 * judges are told the panel does is read what the engine computed, answer in
 * Spanish and offer one action a person executes. Offline, the reading is real
 * (the findings, the totals, the verification and the supplier's own accounts are
 * the generated company's own rows), the answer is assembled from those rows, and
 * the proposal is the same `ActionProposal` the API would send. The part that is
 * missing is the language, and the header says which part that is.
 *
 * Three rows of the generated dataset are read straight from `./mock-data.ts`
 * rather than through `./mock.ts`: the conversation, the actor and the execution.
 * `./mock.ts` exists to compose the payloads the API assembles out of several
 * rows, and these three are already payloads: `ASSISTANT_SESSION` is what
 * `GET /api/v1/assistant/sessions/:id` answers, `ACTOR` is the person every write
 * carries on `X-Actor`, and `EXECUTION` is what the run did on the rail.
 *
 * `assistant.test.ts` drives every branch below with a fixed timestamp, so the
 * offline turn is a pure function of the run and the question: same question, same
 * answer, no clock and no network.
 */

